#!/usr/bin/env node
// Regenerates CHANGELOG.md from the first-parent history of main.
// When PR_NUMBER and PR_TITLE are set (run inside a pull request), that PR is
// listed too so the entry lands in the same PR. Idempotent for the same inputs.
const { execFileSync } = require('child_process');
const fs = require('fs');
const path = require('path');

const repo = process.env.GITHUB_REPOSITORY || 'CFisher46/crafty-keep-sakes';
const SEP = '\x1e';
const FIELD = '\x1f';

const hasRef = (ref) => {
  try {
    execFileSync('git', ['rev-parse', '--verify', '--quiet', ref], { stdio: 'ignore' });
    return true;
  } catch {
    return false;
  }
};
const baseRef = ['origin/main', 'main'].find(hasRef) || 'HEAD';

const log = execFileSync(
  'git',
  ['log', baseRef, '--first-parent', `--format=%h${FIELD}%ad${FIELD}%B${SEP}`, '--date=short'],
  { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 }
);

const entries = [];
for (const raw of log.split(SEP)) {
  if (!raw.trim()) continue;
  const [hash, date, message] = raw.trim().split(FIELD);
  const lines = message.split('\n').map((l) => l.trim());
  const subject = lines[0];

  let pr;
  let title;
  const merge = subject.match(/^Merge pull request #(\d+) from /);
  const squash = subject.match(/^(.*) \(#(\d+)\)$/);
  if (merge) {
    pr = merge[1];
    title = lines.slice(1).find(Boolean) || subject;
  } else if (squash) {
    pr = squash[2];
    title = squash[1];
  } else {
    continue; // direct commits without a PR are not listed
  }
  entries.push({ hash, date, pr, title: title.replace(/\s+/g, ' ') });
}

const pendingPr = process.env.PR_NUMBER;
if (pendingPr && !entries.some((e) => e.pr === pendingPr)) {
  const date = process.env.PR_DATE || new Date().toISOString().slice(0, 10);
  const title = (process.env.PR_TITLE || `Pull request #${pendingPr}`).replace(/\s+/g, ' ').trim();
  entries.unshift({ hash: '', date, pr: pendingPr, title });
}
entries.sort((a, b) => (a.date < b.date ? 1 : a.date > b.date ? -1 : 0));

const byDate = new Map();
for (const e of entries) {
  if (!byDate.has(e.date)) byDate.set(e.date, []);
  byDate.get(e.date).push(e);
}

let out = '# Changelog\n\nAll notable changes merged into `main`. This file is generated by ' +
  '[scripts/generate-changelog.js](scripts/generate-changelog.js) on every pull request; do not edit it by hand.\n';
for (const [date, items] of byDate) {
  out += `\n## ${date}\n\n`;
  for (const e of items) {
    const prLink = `[#${e.pr}](https://github.com/${repo}/pull/${e.pr})`;
    const commitLink = e.hash
      ? `, [\`${e.hash}\`](https://github.com/${repo}/commit/${e.hash})`
      : '';
    out += `- ${e.title} (${prLink}${commitLink})\n`;
  }
}

fs.writeFileSync(path.join(__dirname, '..', 'CHANGELOG.md'), out);
console.log(`CHANGELOG.md written with ${entries.length} entries`);
